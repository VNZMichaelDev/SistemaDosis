-- ============================================================
-- 0019 — CONTEO DE INVENTARIO + REPORTE DE CONSUMO (fase B/C)
-- Fase B: consumo teórico vs. real.
--   Teórico  = recetas × ventas del período (lo que debió gastarse).
--   Real     = teórico + mermas registradas + diferencia del conteo.
--   Pérdida no registrada = stock del sistema − inventario contado
--              (positivo = falta material: posible robo, porción
--              excesiva o merma no anotada).
-- Fase C: indicadores — food cost % (meta 28%–35% de las ventas),
--          compras del período y ranking de mayores pérdidas.
-- ============================================================

create table if not exists conteos_inventario (
  id bigint generated by default as identity primary key,
  fecha date not null default current_date,
  ingrediente_id bigint not null references ingredientes(id) on delete cascade,
  cantidad double precision not null check (cantidad >= 0),
  usuario_id bigint references usuarios(id),
  notas text not null default '',
  created_at timestamptz not null default now()
);

-- Un solo conteo por ingrediente y fecha (volver a contar reemplaza).
create unique index if not exists uq_conteo_fecha_ing
  on conteos_inventario (fecha, ingrediente_id);
create index if not exists idx_conteo_fecha on conteos_inventario (fecha);

alter table conteos_inventario enable row level security;

-- ==================== REPORTE TEÓRICO VS. REAL ====================
-- El handler lo invoca vía: supabaseAdmin().rpc('reporte_consumo', { p_from, p_to })
create or replace function public.reporte_consumo(p_from date, p_to date)
returns jsonb
language sql
as $$
with teorico as (
  -- Lo que las recetas dicen que debió gastarse en las ventas del período
  select ri.ingrediente_id,
         sum(ri.cantidad * dv.cantidad) as cant
    from detalle_venta dv
    join ventas v on v.id = dv.venta_id
    join productos p on p.id = dv.producto_id and p.es_receta
    join receta_ingredientes ri on ri.producto_id = dv.producto_id
   where v.fecha >= p_from
     and v.fecha < (p_to + 1)::timestamp
   group by ri.ingrediente_id
),
mermas_agg as (
  -- Pérdidas ya anotadas en la bitácora (fase A)
  select ingrediente_id,
         sum(cantidad) as cant,
         sum(costo_usd) as costo
    from mermas
   where fecha >= p_from
     and fecha <= p_to
   group by ingrediente_id
),
conteos as (
  -- Último conteo físico por ingrediente hasta el cierre del período
  select distinct on (ingrediente_id)
         ingrediente_id, cantidad, fecha
    from conteos_inventario
   where fecha <= p_to
   order by ingrediente_id, fecha desc, id desc
),
ventas_tot as (
  select coalesce(sum(total_usd), 0) as total
    from ventas
   where fecha >= p_from
     and fecha < (p_to + 1)::timestamp
),
compras_tot as (
  -- Compras de materia prima del período (facturas de proveedor)
  select coalesce(sum(monto_total), 0) as total
    from facturas_proveedor
   where fecha_registro >= p_from
     and fecha_registro < (p_to + 1)::timestamp
     and categoria = 'compra'
)
select jsonb_build_object(
  'ventas_total', (select total from ventas_tot),
  'compras_total', (select total from compras_tot),
  'ingredientes', coalesce((
    select jsonb_agg(jsonb_build_object(
      'ingrediente_id',   i.id,
      'nombre',           i.nombre,
      'unidad',           i.unidad,
      'precio_unitario',  coalesce(i.precio_unitario, 0),
      'stock_actual',     coalesce(i.stock_actual, 0),
      'teorico_cant',     coalesce(t.cant, 0),
      'mermas_cant',      coalesce(m.cant, 0),
      'mermas_costo',     coalesce(m.costo, 0),
      'conteo_cant',      c.cantidad,
      'conteo_fecha',     c.fecha
    ))
    from ingredientes i
    left join teorico t     on t.ingrediente_id = i.id
    left join mermas_agg m  on m.ingrediente_id = i.id
    left join conteos c     on c.ingrediente_id = i.id
    where i.activo
  ), '[]'::jsonb)
) as data;
$$;

revoke execute on function public.reporte_consumo(date, date) from public, anon, authenticated;
grant execute on function public.reporte_consumo(date, date) to service_role;
