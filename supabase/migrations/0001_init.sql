create index if not exists idx_pedido_items_pedido on pedido_items(pedido_id);
create index if not exists idx_pedido_items_producto on pedido_items(producto_id);

create index if not exists idx_ventas_fecha on ventas(fecha desc);
create index if not exists idx_ventas_usuario on ventas(usuario_id);
create index if not exists idx_ventas_pedido on ventas(pedido_id);
create index if not exists idx_ventas_vendedor on ventas(vendedor_id);
create index if not exists idx_detalle_venta_venta on detalle_venta(venta_id);
create index if not exists idx_detalle_venta_producto on detalle_venta(producto_id);
create index if not exists idx_venta_pagos_venta on venta_pagos(venta_id);

create index if not exists idx_credito_ventas_cliente on credito_ventas(cliente_id);
create index if not exists idx_credito_pagos_cliente on credito_pagos(cliente_id);

create index if not exists idx_facturas_prov_proveedor on facturas_proveedor(proveedor_id);
create index if not exists idx_pagos_prov_factura on pagos_proveedor(factura_proveedor_id);

create index if not exists idx_receta_ing_ingrediente on receta_ingredientes(ingrediente_id);
create index if not exists idx_vendedores_usuario on vendedores(usuario_id);

