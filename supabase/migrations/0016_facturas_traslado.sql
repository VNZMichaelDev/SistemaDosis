-- ============================================================
-- 0016 — FACTURAS DE TRASLADO DE MERCANCÍA
-- Facturas emitidas al enviar mercancía de la sucursal principal
-- a otra sucursal. Formato digital de la factura manual.
-- ============================================================

create table if not exists facturas_traslado (
  id bigint generated by default as identity primary key,
  numero text not null unique,
  destinatario text not null default '',
  direccion text not null default '',
  rif text not null default '',
  fecha date not null default current_date,
  subtotal double precision not null default 0,
  total double precision not null default 0,
  notas text not null default '',
  usuario_id bigint references usuarios(id),
  created_at timestamptz not null default now()
);

create table if not exists facturas_traslado_items (
  id bigint generated by default as identity primary key,
  factura_id bigint not null references facturas_traslado(id) on delete cascade,
  producto_id bigint references productos(id) on delete set null,
  descripcion text not null,
  cantidad double precision not null default 1,
  precio_unitario double precision not null default 0,
  importe double precision not null default 0
);

create index if not exists idx_ft_items_factura on facturas_traslado_items(factura_id);

-- Secuencia para número automático FT-XXX
create sequence if not exists facturas_traslado_seq start 1;

alter table facturas_traslado enable row level security;
alter table facturas_traslado_items enable row level security;
