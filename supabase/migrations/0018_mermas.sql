-- ============================================================
-- 0018 — BITÁCORA DE MERMAS Y PÉRDIDAS
-- Registro obligatorio de las pérdidas de materia prima:
--   operativas  → mermas naturales, errores de cocina, vencimientos,
--                 fallas de cadena de frío
--   financieras → consumo de personal no registrado, cortesías no
--                 autorizadas, robos (hormigueo)
-- Cada registro descuenta el stock del ingrediente y guarda el
-- costo al momento de la pérdida (cantidad × precio_unitario).
-- ============================================================

create table if not exists mermas (
  id bigint generated by default as identity primary key,
  fecha date not null default current_date,
  ingrediente_id bigint not null references ingredientes(id),
  cantidad double precision not null check (cantidad > 0),
  costo_usd double precision not null default 0 check (costo_usd >= 0),
  tipo text not null check (tipo in ('operativa','financiera')),
  motivo text not null check (motivo in ('merma_natural','error_cocina','vencimiento','cadena_frio','consumo_personal','cortesia','robo','otro')),
  notas text not null default '',
  usuario_id bigint references usuarios(id),
  created_at timestamptz not null default now()
);

create index if not exists idx_mermas_fecha on mermas (fecha);
create index if not exists idx_mermas_ingrediente on mermas (ingrediente_id);

alter table mermas enable row level security;

-- ==================== REGISTRO ATÓMICO ====================
-- Descuenta stock + inserta en la bitácora en una sola transacción,
-- con el costo calculado con el precio vigente del ingrediente.
-- El handler lo invoca vía: supabaseAdmin().rpc('registrar_merma', {...})
create or replace function public.registrar_merma(
  p_ingrediente_id bigint,
  p_cantidad double precision,
  p_tipo text,
  p_motivo text,
  p_notas text,
  p_usuario_id bigint,
  p_fecha date default current_date
) returns bigint
language plpgsql
as $$
declare
  v_stock double precision;
  v_precio double precision;
  v_costo double precision;
  v_id bigint;
begin
  if p_cantidad is null or p_cantidad <= 0 then
    raise exception 'INVALID_QUANTITY';
  end if;
  if p_tipo is null or p_tipo not in ('operativa', 'financiera') then
    raise exception 'INVALID_TYPE';
  end if;
  if p_motivo is null or p_motivo not in ('merma_natural','error_cocina','vencimiento','cadena_frio','consumo_personal','cortesia','robo','otro') then
    raise exception 'INVALID_REASON';
  end if;

  select stock_actual, precio_unitario
    into v_stock, v_precio
    from ingredientes
    where id = p_ingrediente_id
    for update;

  if not found then
    raise exception 'INGREDIENT_NOT_FOUND';
  end if;
  if v_stock - p_cantidad < 0 then
    raise exception 'INSUFFICIENT_STOCK';
  end if;

  v_costo := round((p_cantidad * coalesce(v_precio, 0))::numeric, 2)::double precision;

  insert into mermas (fecha, ingrediente_id, cantidad, costo_usd, tipo, motivo, notas, usuario_id)
  values (coalesce(p_fecha, current_date), p_ingrediente_id, p_cantidad, v_costo, p_tipo, p_motivo, coalesce(p_notas, ''), p_usuario_id)
  returning id into v_id;

  update ingredientes
     set stock_actual = round((v_stock - p_cantidad)::numeric, 3)::double precision
   where id = p_ingrediente_id;

  return v_id;
end;
$$;

revoke execute on function public.registrar_merma(bigint, double precision, text, text, text, bigint, date) from public, anon, authenticated;
grant execute on function public.registrar_merma(bigint, double precision, text, text, text, bigint, date) to service_role;

-- ==================== ANULACIÓN (DEVUELVE STOCK) ====================
-- Corrige registros erróneos: borra la entrada de la bitácora y
-- devuelve la cantidad al stock del ingrediente.
create or replace function public.anular_merma(p_id bigint)
returns void
language plpgsql
as $$
declare
  v_merma mermas%rowtype;
begin
  select * into v_merma from mermas where id = p_id for update;
  if not found then
    raise exception 'MERMA_NOT_FOUND';
  end if;

  delete from mermas where id = p_id;

  update ingredientes
     set stock_actual = round((stock_actual + v_merma.cantidad)::numeric, 3)::double precision
   where id = v_merma.ingrediente_id;
end;
$$;

revoke execute on function public.anular_merma(bigint) from public, anon, authenticated;
grant execute on function public.anular_merma(bigint) to service_role;
