-- ============================================================
-- 0017 — PAGOS / ABONOS A FACTURAS DE TRASLADO
-- Permite registrar abonos parciales contra una factura de
-- traslado, igual que pagos_proveedor para facturas de proveedor.
-- ============================================================

create table if not exists pagos_traslado (
  id bigint generated by default as identity primary key,
  factura_traslado_id bigint not null references facturas_traslado(id) on delete cascade,
  monto double precision not null,
  notas text not null default '',
  fecha_pago timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists idx_pagos_traslado_factura on pagos_traslado(factura_traslado_id);

alter table pagos_traslado enable row level security;
