-- Contabilidad: gastos, inventario valorizado (captura manual), facturas de proveedor
-- clasificadas (compra/gasto) y módulo de empleados con control de días
-- (tasas según la contadora: prestaciones 60/año, vacaciones 15 disfrute + 15 bono, utilidades 30/año).

-- ==================== GASTOS DEL NEGOCIO ====================
create table if not exists gastos (
  id bigint generated by default as identity primary key,
  fecha date not null default current_date,
  categoria text not null check (categoria in ('alquiler','sueldos','intereses','prestaciones','servicios','impuestos','transporte','marketing','otro')),
  descripcion text not null default '',
  monto_usd double precision not null check (monto_usd >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_gastos_fecha on gastos (fecha);

-- ==================== CIERRES DE INVENTARIO VALORIZADO ====================
-- Captura manual (como la contadora): al inicio y al cierre de cada período.
create table if not exists inventario_cierres (
  id bigint generated by default as identity primary key,
  fecha date not null default current_date,
  tipo text not null check (tipo in ('inicial','final')),
  valor_usd double precision not null check (valor_usd >= 0),
  notas text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_inventario_cierres_fecha on inventario_cierres (fecha, tipo);

-- ==================== FACTURAS DE PROVEEDOR: CATEGORÍA Y FECHA ====================
alter table facturas_proveedor add column if not exists categoria text not null default 'compra' check (categoria in ('compra','gasto'));
alter table facturas_proveedor add column if not exists fecha_documento date not null default current_date;

-- ==================== EMPLEADOS ====================
create table if not exists empleados (
  id bigint generated by default as identity primary key,
  nombre text not null,
  cedula text not null default '',
  cargo text not null default '',
  fecha_ingreso date not null default current_date,
  salario_usd double precision not null default 0,
  activo boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_empleados_activo on empleados (activo);

-- ==================== CONTROL DE DÍAS DE EMPLEADOS ====================
-- tipo: disfrute (vacaciones), bono_vacacional, utilidades, prestaciones
create table if not exists empleado_dias (
  id bigint generated by default as identity primary key,
  empleado_id bigint not null references empleados(id) on delete cascade,
  tipo text not null check (tipo in ('disfrute','bono_vacacional','utilidades','prestaciones')),
  fecha date not null default current_date,
  dias double precision not null check (dias > 0),
  notas text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_empleado_dias_empleado on empleado_dias (empleado_id);
